// Helper functions
export const getTopicsByGradeAndSubject = (grade, subject) =>
  content.filter(c => c.grade === grade && c.subject === subject);

export const getTopicById = (topicId) =>
  content.find(c => c.topic_id === topicId);

export const getTopicByPageNumber = (grade, pageNumber) =>
  content.find(c => c.grade === grade && c.page_numbers.includes(pageNumber));

export const getAllGradesWithContent = () =>
  [...new Set(content.map(c => c.grade))].sort();

export const getSubjectsForGrade = (grade) =>
  [...new Set(content.filter(c => c.grade === grade).map(c => c.subject))];

export default content;
